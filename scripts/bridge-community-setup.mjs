// Configure a reviewed upstream stdio server; no downloader, proxy or game launch.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import os from 'node:os';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pin=JSON.parse(fs.readFileSync(path.join(root,'integrations/hoi4-agent-tools.json'),'utf8'));
const source=path.join(root,pin.sourceDirectory);
const game=path.resolve(process.argv[2]||process.env.HOI4_GAME_DIR||'');
if(!fs.existsSync(path.join(game,'hoi4.exe'))||!fs.existsSync(path.join(game,'documentation')))throw new Error('Supply the installed Windows game root');
const revision=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8',windowsHide:true}).trim();
if(revision!==pin.revision)throw new Error('Upstream revision differs from reviewed pin');
execFileSync('git',['-C',source,'diff','--exit-code','HEAD','--','src','package.json','npm-shrinkwrap.json'],{stdio:'pipe',windowsHide:true});
const entry=path.join(source,'dist/bin/stdio.js');
if(!fs.existsSync(entry))throw new Error('Build the reviewed upstream source first; see COMMUNITY-TOOLS.md');
const local=path.join(root,'.bridge-local/agent-tools');
const configPath=path.join(local,'config.json');
const codexPath=path.join(local,'codex.toml');
const marker='# Managed HOI4 source-analysis integration; generated by bridge-community-setup.mjs';
fs.mkdirSync(local,{recursive:true});fs.mkdirSync(path.dirname(codexPath),{recursive:true});
fs.writeFileSync(configPath,JSON.stringify({version:1,gameRoot:game,modRoots:[],defaultWorkspace:'companion',serverStateRoot:path.join(local,'state'),workspaceStorageRoot:path.join(local,'storage'),jobDeadlineSeconds:120,jobWorkerIdleSeconds:0,workspaces:[{id:'companion',name:'Companion telemetry source',root:path.join(root,'mods/hoi4-companion-telemetry'),gameRoot:game,kind:'mod'}]},null,2)+'\n');
// JSON strings/arrays are valid TOML basic strings/arrays for these generated paths.
const block=`${marker}\n[mcp_servers.${pin.serverName}]\ncommand = ${JSON.stringify(process.execPath)}\nargs = ${JSON.stringify([entry,'--config',configPath])}\ncwd = ${JSON.stringify(root)}\nstartup_timeout_sec = 120\ntool_timeout_sec = 600\nenabled_tools = ${JSON.stringify(pin.enabledTools)}\nenv = { HOI4_AGENT_STDIO_IDLE_EXIT_MINUTES = "30" }\n`;
fs.writeFileSync(codexPath,block);
let registered=false;
if(process.argv.includes('--register-user')){
  const target=path.join(process.env.CODEX_HOME||path.join(os.homedir(),'.codex'),'config.toml');
  const before=fs.existsSync(target)?fs.readFileSync(target,'utf8'):'';
  if(before.includes(block))registered=true;
  else {
    if(/\[\s*mcp_servers\.(?:hoi4_agent_tools|"hoi4_agent_tools"|'hoi4_agent_tools')(?:\.|\s*\])/.test(before))throw new Error('Existing Agent Tools registration differs; review it manually');
    // Append only this MCP registration; do not change trust or permission settings.
    fs.appendFileSync(target,'\n'+block);registered=true;
  }
}
console.log(JSON.stringify({revision,configPath,codexPath,registered,enabledTools:pin.enabledTools,gameLaunched:false},null,2));
